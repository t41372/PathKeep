/** Text for a `schedule.*` key, or null for a key the catalog does not know (the caller falls back to the raw id). */
export function scheduleCopy(key: string | null | undefined): string | null {
  if (!key?.startsWith('schedule.')) return null
  return backend[key.slice('schedule.'.length)] ?? null
}
