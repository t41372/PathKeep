//! Responsibilities: the exhaustive data table for the current archive layout.
//! Not responsible for: traversing directories, interpreting nested formats or changing data.

use crate::*;

/// Database wiring and its encryption purpose travel with the artifact, not caller-side arrays.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct DatabaseSpec {
    pub db: Db,
    pub key: KeyPurpose,
    pub dependencies: &'static [Db],
    pub companions: CompanionFamily,
    /// Only this native header is consulted by reconciliation and snapshot discovery.
    pub primary: bool,
    /// Config saves create these parents before the remaining scaffold directories.
    pub scaffold_parent: Option<u8>,
    pub introduced_in: ArchiveLayout,
}
/// Each row answers every operation explicitly, including deliberate omissions.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ArtifactSpec {
    pub id: ArtifactId,
    pub path: PathRule,
    pub content: ContentClass,
    pub scope: DataScope,
    pub database: Option<DatabaseSpec>,
    /// Non-database keyed formats use this purpose; database purposes are mandatory above.
    pub file_key: Option<KeyPurpose>,
    pub lifecycle: LifecyclePolicies,
}
macro_rules! row {
    ($id:expr, $path:expr, $content:expr, $scope:expr, $database:expr, $file_key:expr;
        open: $open:expr,
        snapshot: $snapshot:expr,
        restore: $restore:expr,
        portable: $portable:expr,
        mode_change: $mode_change:expr,
        at_rest: $at_rest:expr,
        wipe: $wipe:expr,
        usage: $usage:expr,
        retention: $retention:expr,
        health: $health:expr,
        export_target: $export_target:expr,
        conversion: $conversion:expr,
        prevents_new_envelope: $prevents_new_envelope:expr,
        password_change: $password_change:expr,
        move_import: $move_import:expr,
        census: $census:expr,
) => {
        ArtifactSpec {
            id: $id,
            path: $path,
            content: $content,
            scope: $scope,
            database: $database,
            file_key: $file_key,
            lifecycle: LifecyclePolicies {
                open: $open,
                snapshot: $snapshot,
                restore: $restore,
                portable: $portable,
                mode_change: $mode_change,
                at_rest: $at_rest,
                wipe: $wipe,
                usage: $usage,
                retention: $retention,
                health: $health,
                export_target: $export_target,
                conversion: $conversion,
                prevents_new_envelope: $prevents_new_envelope,
                password_change: $password_change,
                move_import: $move_import,
                census: $census,
            },
        }
    };
}

