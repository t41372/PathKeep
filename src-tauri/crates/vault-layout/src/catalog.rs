/// Every storage identity must name its own policy row.
pub const fn db_artifact(db: Db) -> ArtifactId {
    match db {
        Db::Archive => ArtifactId::History,
        Db::SourceEvidence => ArtifactId::SourceEvidence,
        Db::Intelligence => ArtifactId::Intelligence,
        Db::Agent => ArtifactId::Assistant,
        Db::Scratch => ArtifactId::Scratch,
    }
}
/// Lets storage and crypto share the same role/key/dependency mapping.
pub const fn database_spec(db: Db) -> DatabaseSpec {
    match spec(db_artifact(db)).database {
        Some(database) => database,
        None => panic!("database artifact requires database metadata"),
    }
}
