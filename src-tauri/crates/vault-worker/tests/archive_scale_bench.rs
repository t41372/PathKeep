/// Fills the intelligence tables the doctor checks with one derived row per visit, a search-trail
/// member for every eighth visit, and 1,000 derived rows whose visit does not exist.
fn seeded_derived_rows(root: &Path, config: &AppConfig) {
    let ready = root.join("derived-rows-ready");
    if ready.exists() {
        return;
    }
    let paths = project_paths_with_root(root);
    let connection = open_intelligence_connection(&paths, config, None).expect("intelligence");
    let started = Instant::now();
    connection
        .execute_batch(
            "BEGIN;
             DELETE FROM visit_derived_facts;
             DELETE FROM search_trail_members;
             INSERT INTO visit_derived_facts
               (visit_id, profile_id, registrable_domain, canonical_url, computed_at)
             SELECT id, 'bench', '', '', '' FROM archive.visits;
             INSERT INTO visit_derived_facts
               (visit_id, profile_id, registrable_domain, canonical_url, computed_at)
             SELECT id + 1000000000, 'bench', '', '', '' FROM archive.visits LIMIT 1000;
             INSERT INTO search_trail_members (trail_id, profile_id, visit_id, ordinal, role)
             SELECT 'trail-' || (id / 32), 'bench', id, 0, 'query'
             FROM archive.visits WHERE id % 8 = 0;
             COMMIT;",
        )
        .expect("seed derived rows");
    println!("seeded derived rows in {:.1}s", started.elapsed().as_secs_f64());
    std::fs::write(&ready, b"").expect("ready marker");
}

fn bench_doctor(root: &Path, config: &AppConfig) {
    let paths = project_paths_with_root(root);
    unsafe { std::env::set_var("CHB_PROJECT_ROOT", root) };
    let intelligence = open_intelligence_connection(&paths, config, None).expect("intelligence");
    println!("\n## doctor stale-row checks");
    for (table, column) in
        [("visit_derived_facts", "visit_id"), ("search_trail_members", "visit_id")]
    {
        let old = format!(
            "SELECT COUNT(*) FROM {table}
             WHERE {column} NOT IN (SELECT id FROM archive.visits WHERE reverted_at IS NULL)"
        );
        let new = format!(
            "SELECT COUNT(*) FROM {table}
             WHERE NOT EXISTS (
               SELECT 1 FROM archive.visits AS visits
               WHERE visits.id = {table}.{column} AND visits.reverted_at IS NULL
             )"
        );
        for (shape, sql) in [("NOT IN (old)", &old), ("NOT EXISTS (new)", &new)] {
            println!("plan, {table}, {shape}:\n{}", query_plan(&intelligence, sql));
            report_memory(&format!("{table} stale count, {shape}"), 3, || {
                let stale: i64 =
                    intelligence.query_row(sql, [], |row| row.get(0)).expect("stale count");
                assert_eq!(stale, if table == "visit_derived_facts" { 1_000 } else { 0 });
            });
        }
    }
    report_memory("doctor (whole report)", 3, || {
        vault_core::doctor(&paths, config, None).expect("doctor");
    });
}

/// Search events for every eighth visit: 5,000 distinct queries, skewed so a few are common, one
/// in twenty navigational. Times are left NULL and migration 9 is unapplied, so the first read
/// below pays the real upgrade backfill.
fn seed_search_events(connection: &Connection) {
    let started = Instant::now();
    connection
        .execute_batch(
            "BEGIN;
             DELETE FROM search_events;
             INSERT INTO search_events
               (visit_id, profile_id, search_engine, raw_query, normalized_query, query_kind,
                computed_at)
             SELECT id, 'chrome:Default', 'google', 'Query ' || q, 'query ' || q,
                    CASE WHEN id % 160 = 0 THEN 'navigational' ELSE 'keyword' END, ''
             FROM (
               SELECT id, MIN((id * 2654435761) % 1000003 % 5000,
                              (id * 40503) % 999983 % 5000) AS q
               FROM archive.visits WHERE id % 8 = 0
             );
             DROP INDEX IF EXISTS idx_search_events_kind_time;
             UPDATE search_events SET visit_time_ms = NULL;
             DELETE FROM intelligence_schema_migrations WHERE version = 9;
             COMMIT;",
        )
        .expect("seed search events");
    println!("seeded search events in {:.1}s", started.elapsed().as_secs_f64());
}

fn bench_frequent_searches(root: &Path, config: &AppConfig) {
    use vault_core::{DateRange, FrequentSearchesRequest};
    let paths = project_paths_with_root(root);
    unsafe { std::env::set_var("CHB_PROJECT_ROOT", root) };
    let intelligence = open_intelligence_connection(&paths, config, None).expect("intelligence");
    seed_search_events(&intelligence);
    let events: i64 = intelligence
        .query_row("SELECT COUNT(*) FROM search_events", [], |row| row.get(0))
        .expect("count");
    println!("\n## frequent searches ({events} search events)");

    // The synthetic visits end in September 2025.
    let last_day = chrono::NaiveDate::from_ymd_opt(2025, 9, 12).expect("date");
    let request = |days: i64| FrequentSearchesRequest {
        date_range: DateRange {
            start: (last_day - chrono::Duration::days(days - 1)).format("%Y-%m-%d").to_string(),
            end: last_day.format("%Y-%m-%d").to_string(),
        },
        profile_id: None,
        limit: Some(10),
    };
    report("first read: migration 9 backfill + 30-day read", 1, || {
        vault_core::get_frequent_searches(&paths, config, None, &request(30)).expect("read");
    });
    for days in [7, 30, 90, 365] {
        report_memory(&format!("get_frequent_searches, {days} days"), 5, || {
            vault_core::get_frequent_searches(&paths, config, None, &request(days)).expect("read");
        });
    }
    // The same count without a stored time: join each event to its visit, as the other
    // range-scoped search reads (`get_search_queries`, `get_top_search_concepts`) do.
    let joined = "SELECT normalized_query, COUNT(*) AS searches
         FROM search_events
         JOIN archive.visits AS visits ON visits.id = search_events.visit_id
         WHERE search_events.query_kind = 'keyword'
           AND visits.visit_time_ms >= ?1 AND visits.visit_time_ms < ?2
         GROUP BY normalized_query
         ORDER BY searches DESC
         LIMIT 10";
    let plan = query_plan(&intelligence, &joined.replace("?1", "0").replace("?2", "1"));
    println!("plan, joined to archive.visits:\n{plan}");
    for days in [30, 365] {
        let end = START_MS + SPAN_MS;
        let start = end - days * 86_400_000;
        report(&format!("same count joined to archive.visits, {days} days"), 3, || {
            intelligence
                .prepare(joined)
                .expect("prepare")
                .query_map(params![start, end], |row| row.get::<_, String>(0))
                .expect("query")
                .for_each(drop);
        });
    }
}

fn bench_export(root: &Path, config: &AppConfig, key: Option<&str>) {
    use vault_core::{ExportFormat, ExportRequest};
    let paths = project_paths_with_root(root);
    unsafe { std::env::set_var("CHB_PROJECT_ROOT", root) };
    let kind = if key.is_some() { "encrypted" } else { "plaintext" };
    println!("\n## export_history, whole {kind} archive");
    // Export walks History in 1,000-row cursor pages; a page's cost decides the whole walk.
    let mut cursor = None;
    for page in 1..=20 {
        let started = Instant::now();
        let response = vault_core::list_history(
            &paths,
            config,
            key,
            HistoryQuery {
                limit: Some(1_000),
                include_total: Some(false),
                cursor: cursor.clone(),
                ..HistoryQuery::default()
            },
        )
        .expect("export page");
        if page % 5 == 0 {
            println!("  export page {page}: {:.1} ms", started.elapsed().as_secs_f64() * 1000.0);
        }
        cursor = response.next_cursor;
    }
    let formats = std::env::var("PATHKEEP_ARCHIVE_BENCH_EXPORT_FORMATS")
        .unwrap_or_else(|_| "jsonl,html".to_string());
    for name in formats.split(',').filter(|name| !name.trim().is_empty()) {
        let format = match name.trim() {
            "jsonl" => ExportFormat::Jsonl,
            "html" => ExportFormat::Html,
            "markdown" => ExportFormat::Markdown,
            "text" => ExportFormat::Text,
            other => panic!("unknown export format {other}"),
        };
        let mut written = (0, 0);
        report_memory(&format!("export_history, {name}"), 1, || {
            let result = vault_core::export_history(
                &paths,
                config,
                key,
                ExportRequest {
                    export_id: None,
                    query: HistoryQuery::default(),
                    format: format.clone(),
                },
            )
            .expect("export");
            let bytes = std::fs::metadata(&result.path).expect("export file").len();
            std::fs::remove_file(&result.path).expect("remove export");
            written = (result.count, bytes);
        });
        println!("  {} rows, {:.0} MiB file", written.0, written.1 as f64 / (1024.0 * 1024.0));
    }
}

fn query_plan(connection: &Connection, sql: &str) -> String {
    connection
        .prepare(&format!("EXPLAIN QUERY PLAN {sql}"))
        .expect("plan")
        .query_map([], |row| row.get::<_, String>(3))
        .expect("plan rows")
        .map(|row| format!("    {}", row.expect("plan row")))
        .collect::<Vec<_>>()
        .join("\n")
}

/// Keyword search at three frequencies, with and without a date filter, the way the History screen
/// and the AI tools ask for it.
fn bench_search(paths: &ProjectPaths, config: &AppConfig, visits: u64) {
    let page = |q: Option<&str>, include_total: bool| HistoryQuery {
        q: q.map(str::to_string),
        limit: Some(100),
        include_total: Some(include_total),
        ..HistoryQuery::default()
    };
    // "topic 421" matches about 18,000 URLs (titles with "topic 421" and the prefix matches of
    // "421"); "topic 42" is in one title in 500 but with the prefix and trigram matches of "42"
    // about 90,000 URLs match; the rare term is one page in the middle of the id range with a
    // handful of visits; "topic" is in every title.
    let rare = format!("page {}", (visits / 4).max(1) / 3 + 1);
    let last_week = (START_MS + SPAN_MS - 7 * 86_400_000, START_MS + SPAN_MS);
    let first_year = (START_MS, START_MS + 365 * 86_400_000);
    for (label, q, runs, dates) in [
        ("keyword \"topic 421\"", "topic 421", 5, None),
        ("keyword \"topic 42\"", "topic 42", 5, None),
        ("rare keyword", rare.as_str(), 5, None),
        ("\"topic\"", "topic", 3, None),
        ("\"topic\", last 7 days", "topic", 3, Some(last_week)),
        ("\"topic\", first year", "topic", 3, Some(first_year)),
    ] {
        let search = |include_total: bool| HistoryQuery {
            start_time_ms: dates.map(|(start, _)| start),
            end_time_ms: dates.map(|(_, end)| end),
            ..page(Some(q), include_total)
        };
        let grouped = |include_total: bool| HistoryQuery {
            group_by_url: Some(true),
            ..search(include_total)
        };
        report(&format!("{label}, visits, first page, exact total"), runs, || {
            vault_core::list_history(paths, config, None, search(true)).expect("query");
        });
        report(&format!("{label}, visits, first page, no total"), runs, || {
            vault_core::list_history(paths, config, None, search(false)).expect("query");
        });
        report(&format!("{label}, visits newest-first, no total"), runs, || {
            vault_core::list_history(
                paths,
                config,
                None,
                HistoryQuery { sort: Some("newest".into()), ..search(false) },
            )
            .expect("query");
        });
        report(&format!("{label}, pages, first page, no total"), runs, || {
            vault_core::list_history(paths, config, None, grouped(false)).expect("query");
        });
        // The History header's count: the same search with `limit: 1` and the totals.
        report(&format!("{label}, pages, totals (limit 1)"), runs, || {
            vault_core::list_history(
                paths,
                config,
                None,
                HistoryQuery { limit: Some(1), ..grouped(true) },
            )
            .expect("query");
        });
        let first = vault_core::list_history(paths, config, None, grouped(false)).expect("query");
        let totals = vault_core::list_history(
            paths,
            config,
            None,
            HistoryQuery { limit: Some(1), ..grouped(true) },
        )
        .expect("query");
        println!(
            "|   {label}: {} pages, {:?} visits, exact: {}",
            totals.total, totals.total_visits, totals.total_exact
        );
        if first.next_cursor.is_some() {
            report(&format!("{label}, pages, second page by cursor"), runs, || {
                vault_core::list_history(
                    paths,
                    config,
                    None,
                    HistoryQuery { cursor: first.next_cursor.clone(), ..grouped(false) },
                )
                .expect("query");
            });
        }
    }
}

