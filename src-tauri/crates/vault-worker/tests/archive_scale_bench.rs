//! Timing of the IPC read paths against an archive of realistic size.
//!
//! ## Responsibilities
//! - Build a synthetic archive with N visits (default 1,000,000; the product target is 14.4M)
//!   through the real schema, then let the real open path project it into the search database.
//! - Time the per-command costs that decide whether the UI waits: archive open, config load,
//!   `app_snapshot` (plaintext and encrypted), `query_history` with and without the exact total,
//!   source stats, URL detail and the wipe preview.
//! - Seed the intelligence database with derived rows (one per visit, plus stale ones) and time
//!   the doctor's stale-row checks, old query shape beside the current one.
//! - Seed search events (one per eight visits) and time Insights' frequent searches per range,
//!   plus the one-time migration that stores each event's visit time.
//! - Export the whole archive and report time, peak memory and file size per format.
//! - Report peak Rust heap and peak SQLite memory for the calls whose memory matters.
//!
//! ## Not responsible for
//! - Pass/fail thresholds. It prints numbers for `docs/architecture/ipc-performance.md`; it never
//!   runs in CI. Set `PATHKEEP_ARCHIVE_BENCH=1` to run it:
//!
//! ```sh
//! PATHKEEP_ARCHIVE_BENCH=1 PATHKEEP_ARCHIVE_BENCH_VISITS=14400000 \
//!   PATHKEEP_ARCHIVE_BENCH_DIR=/tmp/pathkeep-bench \
//!   cargo test --manifest-path src-tauri/Cargo.toml -p vault-worker \
//!   --test archive_scale_bench --release -- --nocapture
//! ```
//!
//! `PATHKEEP_ARCHIVE_BENCH_DIR` keeps the generated archive between runs (generation at 14.4M
//! takes minutes); without it a temp directory is used and removed.
//!
//! `PATHKEEP_ARCHIVE_BENCH_SECTIONS` picks sections, comma-separated: `reads`, `search`
//! (keyword search at three frequencies), `doctor`, `searches`, `export`, `encrypted`,
//! `encrypted-export`. All but `encrypted-export` run when it is unset; that one seeds a second
//! full-size archive, encrypted, and exports it, because SQLCipher decrypts every page the export
//! reads.
//! `PATHKEEP_ARCHIVE_BENCH_EXPORT_FORMATS` (default `jsonl,html`) picks the export formats; each
//! export file is deleted after it is measured.
//!
//! ## Performance notes
//! - Rows are generated by a fixed linear congruential sequence, so runs are comparable.
//! - Each timing repeats the call and reports the median and the slowest run.

