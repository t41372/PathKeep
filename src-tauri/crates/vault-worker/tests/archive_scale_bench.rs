/// Builds (or reuses) an archive with `visits` visits under `root` and returns its config.
fn seeded_archive(root: &Path, visits: u64, key: Option<&str>) -> AppConfig {
    let paths = project_paths_with_root(root);
    let config = AppConfig {
        initialized: true,
        archive_mode: if key.is_some() { ArchiveMode::Encrypted } else { ArchiveMode::Plaintext },
        selected_profile_ids: PROFILES
            .iter()
            .map(|(browser, profile)| format!("{browser}:{profile}"))
            .collect(),
        ..AppConfig::default()
    };
    let ready = root.join("bench-ready");
    if ready.exists() {
        return config;
    }
    let _ = std::fs::remove_dir_all(root);
    save_config(&paths, &config).expect("save config");
    let started = Instant::now();
    insert_rows(&paths, &config, key, visits);
    println!("seeded {visits} visits in {:.1}s", started.elapsed().as_secs_f64());

    // A fresh open in this process projects the new rows into the search database, the same
    // first-launch path a real upgrade takes.
    let started = Instant::now();
    drop(open_archive_connection(&paths, &config, key).expect("projecting open"));
    println!("projected search documents in {:.1}s", started.elapsed().as_secs_f64());
    std::fs::write(&ready, b"").expect("ready marker");
    config
}

fn insert_rows(paths: &ProjectPaths, config: &AppConfig, key: Option<&str>, visits: u64) {
    let mut connection = open_archive_connection(paths, config, key).expect("open archive");
    let urls = (visits / 4).max(1);
    let transaction = connection.transaction().expect("transaction");
    transaction
        .execute(
            "INSERT INTO runs (id, run_type, trigger, started_at, finished_at, status, due_only)
             VALUES (1, 'backup', 'manual', '2026-01-01T00:00:00Z', '2026-01-01T00:10:00Z',
                     'success', 0)",
            [],
        )
        .expect("run");
    for (index, (browser, profile)) in PROFILES.iter().enumerate() {
        transaction
            .execute(
                "INSERT INTO source_profiles (id, browser_kind, profile_name, profile_path,
                   discovered_at, enabled, profile_key)
                 VALUES (?1, ?2, ?3, '/bench', '2026-01-01T00:00:00Z', 1, ?4)",
                params![index as i64 + 1, browser, profile, format!("{browser}:{profile}")],
            )
            .expect("profile");
    }
    {
        let mut insert_url = transaction
            .prepare(
                "INSERT INTO urls (id, url, title, visit_count, typed_count, first_visit_ms,
                   first_visit_iso, last_visit_ms, last_visit_iso, source_profile_id,
                   created_by_run_id, source_url_id, hidden, registrable_domain)
                 VALUES (?1, ?2, ?3, 0, 0, ?4, '', ?4, '', ?5, 1, ?1, 0, ?6)",
            )
            .expect("url statement");
        for id in 1..=urls {
            let domain = format!("site{}.example", id % DOMAINS);
            insert_url
                .execute(params![
                    id as i64,
                    format!("https://{domain}/page/{id}"),
                    format!("Page {id} about topic {}", id % 500),
                    START_MS,
                    profile_of(id),
                    domain,
                ])
                .expect("url");
        }
        let mut insert_visit = transaction
            .prepare(
                "INSERT INTO visits (url_id, source_visit_id, visit_time_ms, visit_time_iso,
                   transition_type, visit_duration_ms, source_profile_id, created_by_run_id)
                 VALUES (?1, ?2, ?3, '', 805306368, 0, ?4, 1)",
            )
            .expect("visit statement");
        let mut state: u64 = 0x2545_f491_4f6c_dd1d;
        for index in 0..visits {
            state = state.wrapping_mul(6_364_136_223_846_793_005).wrapping_add(1);
            // Skewed toward low ids so url 1 is the busiest page, like a real start page.
            let url_id = 1 + ((state >> 33) % urls).min((state >> 40) % urls);
            let time = START_MS + (index as i64) * (SPAN_MS / visits as i64);
            insert_visit
                .execute(params![url_id as i64, index.to_string(), time, profile_of(url_id)])
                .expect("visit");
        }
    }
    transaction
        .execute(
            "UPDATE runs SET stats_json = json_object(
               'totalProfiles', 3, 'totalUrls', ?1, 'totalVisits', ?2, 'totalDownloads', 0,
               'earliestVisitAt', '2020-09-13T12:26:40Z', 'latestVisitAt', '2025-09-12T12:26:40Z')
             WHERE id = 1",
            params![urls as i64, visits as i64],
        )
        .expect("cached totals");
    transaction.commit().expect("commit");
}

fn profile_of(url_id: u64) -> i64 {
    (url_id % PROFILES.len() as u64) as i64 + 1
}

/// Runs `call` `iterations` times and prints the median and slowest duration.
fn report(label: &str, iterations: usize, mut call: impl FnMut()) {
    let mut samples: Vec<Duration> = (0..iterations)
        .map(|_| {
            let started = Instant::now();
            call();
            started.elapsed()
        })
        .collect();
    samples.sort();
    let median = samples[samples.len() / 2];
    let slowest = samples[samples.len() - 1];
    println!(
        "| {label:<55} | median {:>9.2} ms | max {:>9.2} ms |",
        median.as_secs_f64() * 1000.0,
        slowest.as_secs_f64() * 1000.0
    );
}

/// Like [`report`], plus the peak memory above the starting point: Rust heap (counted by
/// [`CountingAllocator`]) and SQLite's own allocations (page cache, temporary indexes, sorters),
/// which do not go through the Rust allocator.
fn report_memory(label: &str, iterations: usize, mut call: impl FnMut()) -> (usize, i64) {
    let mut samples = Vec::with_capacity(iterations);
    let mut peak_heap = 0usize;
    let mut peak_sqlite = 0i64;
    for _ in 0..iterations {
        let heap_start = HEAP_CURRENT.load(Ordering::Relaxed);
        HEAP_PEAK.store(heap_start, Ordering::Relaxed);
        // SAFETY: plain reads/resets of SQLite's global memory counters.
        let sqlite_start = unsafe { rusqlite::ffi::sqlite3_memory_used() };
        unsafe { rusqlite::ffi::sqlite3_memory_highwater(1) };
        let started = Instant::now();
        call();
        samples.push(started.elapsed());
        peak_heap = peak_heap.max(HEAP_PEAK.load(Ordering::Relaxed).saturating_sub(heap_start));
        let sqlite_high = unsafe { rusqlite::ffi::sqlite3_memory_highwater(0) };
        peak_sqlite = peak_sqlite.max(sqlite_high - sqlite_start);
    }
    samples.sort();
    let mib = |bytes: f64| bytes / (1024.0 * 1024.0);
    println!(
        "| {label:<55} | median {:>9.2} ms | max {:>9.2} ms | heap +{:>8.1} MiB | sqlite +{:>8.1} MiB |",
        samples[samples.len() / 2].as_secs_f64() * 1000.0,
        samples[samples.len() - 1].as_secs_f64() * 1000.0,
        mib(peak_heap as f64),
        mib(peak_sqlite as f64),
    );
    (peak_heap, peak_sqlite)
}

static HEAP_CURRENT: AtomicUsize = AtomicUsize::new(0);
static HEAP_PEAK: AtomicUsize = AtomicUsize::new(0);

/// The system allocator plus a live-bytes counter and a resettable peak, so a call's peak heap
/// can be read without the process-lifetime high-water mark that `ru_maxrss` gives.
struct CountingAllocator;

impl CountingAllocator {
    fn grew(size: usize) {
        let now = HEAP_CURRENT.fetch_add(size, Ordering::Relaxed) + size;
        HEAP_PEAK.fetch_max(now, Ordering::Relaxed);
    }
}

// SAFETY: every call is forwarded to `System`; the counters never affect the returned memory.
unsafe impl GlobalAlloc for CountingAllocator {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        let pointer = unsafe { System.alloc(layout) };
        if !pointer.is_null() {
            Self::grew(layout.size());
        }
        pointer
    }

    unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
        let pointer = unsafe { System.alloc_zeroed(layout) };
        if !pointer.is_null() {
            Self::grew(layout.size());
        }
        pointer
    }

    unsafe fn dealloc(&self, pointer: *mut u8, layout: Layout) {
        unsafe { System.dealloc(pointer, layout) };
        HEAP_CURRENT.fetch_sub(layout.size(), Ordering::Relaxed);
    }

    unsafe fn realloc(&self, pointer: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {
        let grown = unsafe { System.realloc(pointer, layout, new_size) };
        if !grown.is_null() {
            HEAP_CURRENT.fetch_sub(layout.size(), Ordering::Relaxed);
            Self::grew(new_size);
        }
        grown
    }
}

#[global_allocator]
static ALLOCATOR: CountingAllocator = CountingAllocator;

/// Failure mode (f): use the real export and allocator, comparing two archive sizes in an
/// otherwise idle integration-test process. This guards against collecting rows/strings again.
#[test]
fn export_heap_stays_bounded_as_archive_grows() {
    // Large opt-in benchmarks run alone so their allocator measurements remain comparable.
    if std::env::var("PATHKEEP_ARCHIVE_BENCH").as_deref() == Ok("1")
        || std::env::var("PATHKEEP_IMPORT_BATCH_BENCH").as_deref() == Ok("1")
    {
        return;
    }
    let root = tempfile::tempdir_in(std::env::current_dir().unwrap()).unwrap();
    let mut peaks = Vec::new();
    for visits in [10_000, 100_000] {
        let archive_root = root.path().join(format!("bounded-{visits}"));
        let config = seeded_archive(&archive_root, visits, None);
        let paths = project_paths_with_root(&archive_root);
        let (heap, _) = report_memory("bounded export heap", 1, || {
            let result = vault_core::export_history(
                &paths,
                &config,
                None,
                vault_core::ExportRequest {
                    export_id: None,
                    query: HistoryQuery::default(),
                    format: vault_core::ExportFormat::Jsonl,
                },
            )
            .unwrap();
            assert_eq!(result.count as u64, visits);
            std::fs::remove_file(result.path).unwrap();
        });
        assert!(heap < 2 * 1024 * 1024, "export allocated {heap} bytes above baseline");
        peaks.push(heap);
    }
    assert!(peaks[1] <= peaks[0] + 256 * 1024, "export heap grew with archive size: {peaks:?}");
}
